"""Metrics and confusion matrices.

Deliberately reports macro-F1, per-class F1 and FPR alongside accuracy, because
the survey's finding is that accuracy alone conceals minority-class failure.
Accuracy is recorded but should never be reported on its own.
"""
from __future__ import annotations
import numpy as np
from sklearn.metrics import (accuracy_score, confusion_matrix, f1_score,
                             precision_score, recall_score)


def compute(y_true, y_pred, classes, y_train=None):
    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)
    labels = list(range(len(classes)))

    out = {
        "accuracy": float(accuracy_score(y_true, y_pred)),
        "macro_f1": float(f1_score(y_true, y_pred, average="macro", labels=labels, zero_division=0)),
        "weighted_f1": float(f1_score(y_true, y_pred, average="weighted", labels=labels, zero_division=0)),
        "macro_precision": float(precision_score(y_true, y_pred, average="macro", labels=labels, zero_division=0)),
        "macro_recall": float(recall_score(y_true, y_pred, average="macro", labels=labels, zero_division=0)),
    }
    if len(classes) == 2:
        out["binary_f1"] = float(f1_score(y_true, y_pred, pos_label=1, zero_division=0))

    # Macro-F1 restricted to classes the model could actually have learned and
    # that the test fold actually contains. On corpora generated by running
    # attack scenarios one after another -- BoT-IoT is one -- a temporal split
    # puts whole classes on one side only. Unrestricted macro-F1 then charges
    # the model zero for classes it never saw in training and for classes with
    # no test support, which measures the dataset's construction rather than the
    # model. Both figures are reported; they should be read together.
    if y_train is not None:
        learnable = sorted(set(np.unique(y_train)) & set(np.unique(y_true)))
        out["n_classes_learnable"] = int(len(learnable))
        out["macro_f1_learnable"] = (
            float(f1_score(y_true, y_pred, average="macro", labels=learnable,
                           zero_division=0)) if learnable else float("nan"))
    cm = confusion_matrix(y_true, y_pred, labels=labels)
    out["fpr"] = _fpr(cm, benign_index=_benign_index(classes))
    out["support_test"] = int(len(y_true))
    out["n_classes_present"] = int(len(np.unique(y_true)))
    return out, per_class(y_true, y_pred, classes, cm), cm


def _benign_index(classes):
    for i, c in enumerate(classes):
        if str(c).strip().lower() in ("benign", "normal", "0", "none", "background"):
            return i
    return 0


def _fpr(cm, benign_index):
    """Share of benign flows misclassified as any attack -- the false alarm rate."""
    if benign_index >= cm.shape[0]:
        return float("nan")
    row = cm[benign_index]
    total = row.sum()
    if total == 0:
        return float("nan")
    return float((total - row[benign_index]) / total)


def per_class(y_true, y_pred, classes, cm=None):
    labels = list(range(len(classes)))
    if cm is None:
        cm = confusion_matrix(y_true, y_pred, labels=labels)
    f1s = f1_score(y_true, y_pred, average=None, labels=labels, zero_division=0)
    precs = precision_score(y_true, y_pred, average=None, labels=labels, zero_division=0)
    recs = recall_score(y_true, y_pred, average=None, labels=labels, zero_division=0)
    support = cm.sum(axis=1)
    rows = []
    for i, c in enumerate(classes):
        rows.append({
            "class": str(c), "support": int(support[i]),
            "precision": float(precs[i]), "recall": float(recs[i]), "f1": float(f1s[i]),
        })
    return rows


def confusion_long(cm, classes):
    """Confusion matrix in long form: one row per (true, predicted) cell.

    Long form rather than a wide matrix because runs have different class sets,
    so a single tidy file can hold every run and be pivoted per run later.
    Zero cells are dropped to keep the file small.
    """
    rows = []
    for i, t in enumerate(classes):
        for j, p in enumerate(classes):
            c = int(cm[i, j])
            if c:
                rows.append({"true_class": str(t), "pred_class": str(p), "count": c})
    return rows